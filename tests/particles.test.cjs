const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const sandbox = {};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(__dirname, '../extras/sparkles/Particles.js'), 'utf8'), sandbox);
const points = sandbox.pointsBetween;
const a = {screen: 'DP-1', x: 10, y: 20, width: 1920, height: 1080};
const b = {...a, x: 70};
assert.equal(points(null, a, 12, 5).length, 1);
assert.equal(points(a, a, 12, 5).length, 0);
assert.equal(points(a, {...a, x: 15}, 12, 5).length, 0);
assert.equal(points(a, b, 12, 5).length, 5);
assert.equal(points(a, b, 12, 5).at(-1).x, 70);
assert.equal(points(a, {...a, x: 300}, 12, 5).length, 5);
assert.equal(points(a, {...a, x: 1800}, 12, 5).length, 1);
assert.equal(points(a, {...a, screen: 'DP-2'}, 12, 5).length, 1);
assert.equal(points(a, b, 12, 0).length, 0);
console.log('9 particle geometry checks passed');
